#!/usr/bin/env node
// Write ASSETS.md: every file under packs/*/assets with how it was made, so
// the provenance of each image, drawing, PDF and CAD model is on record.
//
//   node tools/build-assets-md.mjs
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const METHOD = {
  images: ['Product photos', 'Made locally with FLUX.2-klein-4B (Apache-2.0, by Black Forest Labs). Main photo `<sku>.jpg` (`tools/build-photos.py`): a simple 3D model of the product (`tools/photo/models/<pack>_*.py`) is rendered in Blender, and the model draws a studio photo from that render and a written description, image-to-image at strength 0.3. Colour variants are the model\'s photo recoloured; size variants reuse it. Close-up `<sku>-2.jpg` (`tools/build-scenes.py`): the edit model puts the finished photo into the setting written in `tools/photo/scenes/<pack>.py`. Models and prompts are recorded in `tools/photo/state/`. The products are fictional; the photos are AI-generated and show no real product or brand.'],
  categories: ['Category images', 'Made by `tools/build-categories.py`: the FLUX.2-klein-4B edit model, run locally, puts three product photos of the category together into one group photo. AI-generated; no real product or brand.'],
  drawings: ['Technical drawings', 'Hand-made sheets from `tools/docs/<pack>.mjs` (`tools/build-docs.mjs`), and automatic sheets (`tools/build-drawings.py`) projected in Blender from the same 3D models as the photos: front, side and top view with hidden lines removed, SVG plus PDF.'],
  downloads: ['Data sheets', 'One-page sheets generated from the product data and the product photo by `tools/build-datasheets.mjs` (no browser, `tools/sheet-pdf.mjs`).'],
  logos: ['Manufacturer logos', 'Flat vector wordmarks for the fictional makers, generated by `tools/build-logos.py` (SVG, plus a PNG made with rsvg-convert).'],
  cad: ['3D model (STEP)', 'Built from our own dimensions with CadQuery by `tools/cad/<pack>.py`. Simplified: correct outer dimensions, no modelled thread.'],
};

const lines = [
  '# Assets and where they come from',
  '',
  'Every image, drawing, data sheet and 3D model in this repository was made for it by revenexx by the scripts named below. Nothing is copied, traced or downloaded from a manufacturer, a CAD portal or a stock library. The product photos are AI-generated from our own 3D models, as described under each pack. All products, makers and companies are fictional; every PDF says so on the page.',
  '',
  'Licence: the same as the rest of the data, see [LICENSE-DATA](LICENSE-DATA).',
  '',
];
for (const pack of readdirSync(join(ROOT, 'packs')).sort()) {
  const root = join('packs', pack, 'assets');
  if (!existsSync(join(ROOT, root))) continue;
  const kinds = readdirSync(join(ROOT, root)).sort();
  lines.push(`## ${pack}`, '');
  for (const kind of kinds) {
    const [title, how] = METHOD[kind] ?? [kind, ''];
    const files = readdirSync(join(ROOT, root, kind)).filter((f) => statSync(join(ROOT, root, kind, f)).isFile()).sort();
    lines.push(`### ${title}`, '', how.replace('<pack>', pack), '', '| File | Size |', '| --- | --- |');
    for (const f of files) lines.push(`| \`${join(root, kind, f)}\` | ${Math.ceil(statSync(join(ROOT, root, kind, f)).size / 1024)} KB |`);
    lines.push('');
  }
}
writeFileSync(join(ROOT, 'ASSETS.md'), lines.join('\n'));
console.log('  ASSETS.md');
